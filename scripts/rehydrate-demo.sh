#!/bin/sh
# 유출 이후 "유지·식별·복원"을 한 번에 증명하는 데모 —
# 문서 하나(원본)를 유출 후 네 갈래로 변형시키고, 저항 사다리의 각 단이
# 하나씩 걸려 정체성이 되살아나는 것을 보여준다.
#
#   A. 무수정 사본            → content hash          [exact]   원본 라벨 그대로 회수
#   B. 재저장/형식 변환본     → text hash             [text]    바이트 달라도 라벨 회수
#   C. 일부 수정본(유사)      → 지문 + 상속 복원      [inherited] File ID·등급·태그 승계 ★
#   D. 무관 문서              → 미식별                [not_found] 아무거나 복원하지 않음(오탐 방지)
#
# 사용: ./scripts/rehydrate-demo.sh [출력디렉터리]
# 전제: 서버 가동(./deploy/run-demo.sh), bin/lm 빌드.
set -e
cd "$(dirname "$0")/.."
export LM_SERVER="${LM_SERVER:-http://localhost:8090}"
W="${1:-$HOME/LedgerMarker/demo-rehydrate}"
LM=./bin/lm
[ -x "$LM" ] || { echo "bin/lm 없음 — go build -o bin/lm ./cmd/lm 먼저"; exit 1; }

rm -rf "$W"; mkdir -p "$W"
NONCE="$(date +%s)"   # 실행마다 새 문서 → 원장 멱등·지문 충돌 회피
echo "출력 디렉터리: $W   (실행 ID: $NONCE)"
echo

# ── 원본 생성 (등급 S, 태그) ─────────────────────────────────
# 실행 ID를 여러 조항에 새겨 넣는다 — 반복 실행 시 이전 실행분과 지문이
# 겹치지 않게 하여(교차 매칭 방지) 이번 실행의 원본이 정확히 부모로 잡히게 한다.
BODY="제1조(목적) 이 규정[$NONCE-A]은 문서의 보안등급 분류와 취급에 관한 사항을 정함을 목적으로 한다.
제2조(정의) 비밀이란 국가안전보장에 관련되어 누설될 경우 유해로운 결과를 초래할 우려가 있는 사항을 말한다.
제3조(등급) 보안등급[$NONCE-B]은 비밀(C)·민감(S)·공개(O)의 세 단계로 구분하며, 각 문서에는 하나의 등급만 부여한다.
제4조(취급) 각급 기관의 장은 문서의 보안등급에 따라 열람·복제·반출을 통제하여야 한다.
제5조(검증) 게이트 운영 부서[$NONCE-C]는 문서 반출 전 라벨과 원장을 대조하여 진위를 검증하여야 한다.
제6조(정본) 이 문서의 문서고 정본 식별자는 $NONCE 이며 원본 대장에 등재된다."
printf '%s\n' "$BODY" > "$W/원본.txt"

echo "══ 0. 원본 발급 (등급 S · 태그: 인사,대외비 · 지문·텍스트해시 색인) ══"
"$LM" issue "$W/원본.txt" --grade S >/dev/null
"$LM" verify "$W/원본.txt" 2>/dev/null | sed 's/^/   /' || true
echo

# ── 네 갈래 변형 생성 ────────────────────────────────────────
# A. 무수정 사본 (라벨 없이 본문만 복사 — USB/메일로 새어나간 사본)
cp "$W/원본.txt" "$W/A_무수정사본.txt"

# B. 재저장/형식 변환본: 본문 텍스트는 동일, 바이트만 다름(줄바꿈·공백 재배치)
printf '%s' "$BODY" | tr '\n' ' ' | sed 's/  */ /g' > "$W/B_재저장본.txt"

# C. 일부 수정본: 조항 한 줄 추가 (유사도 높음)
{ printf '%s\n' "$BODY"; printf '%s\n' "제7조(부칙) 이 규정은 공포한 날부터 시행한다."; } > "$W/C_수정본.txt"

# D. 무관 문서
printf '%s\n' "오늘 점심은 김치찌개였다. 주말에는 북한산 등산을 다녀올 계획이다. 날씨가 좋았으면 한다." > "$W/D_무관문서.txt"

restore() { # <설명> <파일> [--rehydrate]
  echo "══ $1 ══"
  # $3 는 선택 플래그(--rehydrate). 비어 있으면 인자로 넘어가지 않도록 비인용 확장.
  if "$LM" restore "$2" $3 2>&1 | sed 's/^/   /'; then :; else echo "   (복원 안 됨 — 위 사유 참조)"; fi
  echo
}

echo "───────────── 유출 이후 복원 ─────────────"
echo
restore "A. 무수정 사본 → 원장 정확 일치로 원본 라벨 회수"        "$W/A_무수정사본.txt"
restore "B. 재저장/형식 변환본 → 텍스트 해시로 원본 라벨 회수"    "$W/B_재저장본.txt"
restore "C. 일부 수정본 → 지문으로 원본 식별 → 귀속 상속 복원 ★" "$W/C_수정본.txt" --rehydrate
restore "D. 무관 문서 → 미식별(오탐 방지)"                        "$W/D_무관문서.txt" --rehydrate

echo "───────────── 계보(족보) — 원본에서 상속 복원된 수정본까지 ─────────────"
"$LM" lineage "$W/C_수정본.txt" --tree 2>/dev/null | sed 's/^/   /' || \
  echo "   (계보 표시는 수정본 사이드카가 필요 — 위 C 복원 결과 참조)"
echo
echo "완료. 산출물: $W (.lmsig 사이드카가 각 사본 옆에 복원됨)"
